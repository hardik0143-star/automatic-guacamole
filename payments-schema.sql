-- Tiny Tiffin Razorpay payment records.
-- Run in the Supabase SQL Editor. No anon/authenticated policies are intentionally created.
create table if not exists public.payment_orders (
  id bigint generated by default as identity primary key,
  order_id text not null unique,
  product_id text not null,
  amount_paise bigint not null check (amount_paise > 0),
  currency text not null default 'INR',
  buyer_email text not null,
  status text not null default 'created',
  payment_id text unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.payment_subscriptions (
  id bigint generated by default as identity primary key,
  subscription_id text not null unique,
  product_id text not null,
  plan_id text not null,
  buyer_email text not null,
  status text not null default 'created',
  last_payment_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.payment_webhook_events (
  event_id text primary key,
  event_name text not null,
  entity_id text,
  received_at timestamptz not null default now()
);

alter table public.payment_orders enable row level security;
alter table public.payment_subscriptions enable row level security;
alter table public.payment_webhook_events enable row level security;

-- Only server-side functions using SUPABASE_SERVICE_ROLE_KEY should access these tables.
-- Never expose the service-role key in browser code or client-side environment variables.
